ثامناً: محرك الذكاء الاصطناعي

أنشئ طبقة برمجية مستقلة مسؤولة عن التواصل مع نموذج الذكاء الاصطناعي.

اختر نموذجاً أو خدمة تدعم:

- فهم النصوص العربية.
- إنشاء الملخصات.
- توليد الأسئلة والأجوبة.
- تحليل الصور عند الحاجة.
- إخراج نتائج منظمة.
- التعامل مع النصوص الطويلة عند تقسيمها إلى أجزاء.

إذا لم تتوفر مفاتيح API، أنشئ التكامل البرمجي بطريقة تسمح بإضافة المفتاح لاحقاً، مع توضيح خطوات الإعداد.

لا تضع مفاتيح API السرية داخل كود الواجهة الأمامية أو ملفات JavaScript التي يستطيع المستخدم الوصول إليها.

استخدم خادماً خلفياً أو وظائف خادمية Serverless لحماية المفاتيح.

أنشئ طبقة اتصال قابلة لتبديل مزود الذكاء الاصطناعي دون الحاجة إلى إعادة بناء التطبيق بالكامل.

معالجة الصفحات الطويلة

إذا كانت الصور تحتوي على عدد كبير من الصفحات:

1. قسّم النص المستخرج إلى أجزاء مناسبة.
2. لخّص كل جزء على حدة.
3. احتفظ بالتعاريف والأرقام والتعدادات المهمة.
4. اجمع الملخصات الجزئية في ملخص موحد.
5. أنشئ الأسئلة من المحتوى الكامل بعد تنظيمه.
6. امنع تكرار الأسئلة المتشابهة قدر الإمكان.

إذا تجاوز حجم المحتوى الحدود التي تسمح بها الخدمة، يجب تقسيمه بطريقة منهجية بدلاً من حذف أجزاء منه دون علم المستخدم.

