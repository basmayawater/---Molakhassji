2. المرحلة الدراسية

قائمة اختيار اختيارية:

- ابتدائي.
- متوسط.
- إعدادي.
- جامعي.
- دراسة عليا.
- أخرى.

إذا لم يكن المحتوى مدرسياً، يستطيع المستخدم ترك هذا الحقل فارغاً.

3. لغة المحتوى

- العربية.
- الإنجليزية.
- لغات أخرى بحسب قدرة خدمة المعالجة.

يجب أن تكون العربية هي اللغة الافتراضية.

4. نوع النتيجة

اسمح للمستخدم باختيار نوع واحد أو أكثر:

- ملخص مختصر.
- ملخص شامل.
- أسئلة وأجوبة.
- أسئلة امتحانية.
- تعاريف ومصطلحات.
- تعاليل وأسباب ونتائج.
- أكمل الفراغات.
- صح أو خطأ.
- اختيار من متعدد.
- شرح مبسّط.
- نقاط مهمة للحفظ.

5. مستوى التفصيل

وفّر ثلاثة خيارات:

- مختصر.
- متوسط.
- مفصل.

