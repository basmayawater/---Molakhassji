إذا لم يتمكن المتصفح من تشغيل الكاميرا، وفّر بديلاً مناسباً باستخدام إمكانات رفع الصور في الجهاز.

الخيار الثاني: رفع الصور

عندما يضغط المستخدم على «ارفع صوراً من الاستوديو»، افتح منتقي الملفات في الهاتف.

المتطلبات:

- السماح باختيار صورة واحدة أو عدة صور.
- دعم صيغ JPEG وJPG وPNG وWebP، بحسب إمكانات البيئة.
- التحقق من نوع الملف وحجمه.
- عرض معاينة لكل صورة.
- إمكانية حذف الصور أو إعادة ترتيبها.
- الحفاظ على ترتيب الصفحات الذي يحدده المستخدم.
- التعامل مع الصور الكبيرة بطريقة لا تؤدي إلى تجميد الواجهة.

لا تبدأ عملية التحليل حتى يضغط المستخدم على زر «ابدأ التلخيص».

