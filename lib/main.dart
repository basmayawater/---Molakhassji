تاسعاً: قواعد إنشاء الملخص

يجب أن يتبع الذكاء الاصطناعي القواعد التالية:

1. الاعتماد على محتوى الصور بوصفه المصدر الأساسي للإجابة.
2. المحافظة على المعنى الأصلي للمعلومات.
3. عدم حذف التعريفات أو القواعد الأساسية المهمة.
4. الحفاظ على الأسماء والأرقام والتواريخ والمصطلحات.
5. عدم اختراع معلومات أو نسبتها إلى الكتاب دون سند.
6. عدم تكرار الفكرة نفسها بصيغ متعددة دون فائدة.
7. استخدام لغة واضحة تناسب المستوى الدراسي المحدد.
8. المحافظة على المصطلحات العلمية المهمة.
9. التفريق بين المعلومة الصريحة والاستنتاج.
10. الإشارة إلى أي جزء غير واضح أو غير مقروء.
11. عدم تحويل المعلومات الاحتمالية إلى حقائق مؤكدة.
12. عند وجود تعارض أو غموض في النص، توضيح ذلك بدلاً من اختلاق حل.

إذا طلب المستخدم شرحاً إضافياً من خارج الكتاب، يمكن تقديمه في قسم مستقل بعنوان «شرح إضافي»، مع تمييزه بوضوح عن الملخص المستخرج من الصفحات.

