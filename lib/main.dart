عاشراً: نظام الأسئلة والأجوبة

أنشئ الأسئلة والأجوبة بطريقة منظمة وسهلة للمراجعة.

أنواع الأسئلة

أ. أسئلة مباشرة

مثال:

س: ما تعريف الخلية؟

ج: يكتب التطبيق التعريف المستخرج من النص الذي رفعه المستخدم.

ب. أسئلة التعاريف

استخراج جميع المصطلحات التي عرّفها الكتاب.

ج. أسئلة التعداد

مثال:

س: اذكر أنواع ...؟

ج: يعرض الأنواع بالترتيب الوارد في المادة.

د. أسئلة التعليل

مثال:

س: لماذا يحدث ...؟

ج: يقدم السبب الذي يذكره النص.

إذا لم يتضمن المحتوى سبباً واضحاً، فلا يخترع التطبيق سبباً وينسبه إلى الكتاب.

هـ. أكمل الفراغات

أنشئ جملًا تعليمية تحتوي على فراغات تغطي المعلومات الأساسية.

و. صح أو خطأ

أنشئ عبارات صحيحة وأخرى خاطئة، مع توفير التصحيح والشرح عند الحاجة.

ز. الاختيار من متعدد

أنشئ سؤالاً مع عدة خيارات، وحدد الإجابة الصحيحة داخلياً.

يجب أن تكون الخيارات الخاطئة معقولة ولكن غير مضللة، وألا يوجد أكثر من جواب صحيح إلا إذا أوضح السؤال ذلك.

قواعد صياغة الأسئلة

- ترتيب الأسئلة بحسب تسلسل المادة.
- استخدام لغة واضحة.
- تجنب الأسئلة الغامضة.
- عدم تكرار السؤال نفسه.
- عدم إنشاء إجابات لا يدعمها المحتوى.
- مراعاة المستوى الدراسي.
- تغطية جميع الأفكار الأساسية في الصفحات.

إذا كان السؤال يحتاج إلى معلومات غير موجودة في الصور، فلا تعرض إجابته على أنها مستخرجة من الكتاب.

